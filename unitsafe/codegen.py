"""Code generator: the checked tree to plain Python (build guide Part 9, G1-G8, D14, D15).

It never makes a unit decision of its own: every number, label and conversion
was worked out by the checker.
"""
import builtins
import keyword

from . import ast_nodes as A
from .runtime import US_PRINT_SOURCE

RESERVED = set(keyword.kwlist) | set(dir(builtins)) | {'math', 'us_print', 'us_fmt'}


def py_name(name: str) -> str:                                        # G5, D15
    return name + '_' if name in RESERVED or name.endswith('_') else name


def num_text(x) -> str:                                               # G8
    return repr(float(x))


class Generator:
    def run(self, program, filename: str = 'program.us') -> str:
        self.lines = []
        self.level = 0
        self.line_map = {}                    # python line -> UnitSafe line
        self.raw(f'# Generated by UnitSafe from {filename}. Do not edit.')    # G7
        self.raw('import math')
        for line in US_PRINT_SOURCE.split('\n'):
            self.raw(line)
        for st in program.body:                                        # hoisted defs (D8)
            if isinstance(st, A.FnDecl):
                self.stmt(st)
                self.raw('')
        for st in program.body:
            if not isinstance(st, (A.FnDecl, A.UnitDecl, A.KindDecl)):
                self.stmt(st)
        return '\n'.join(self.lines).rstrip('\n') + '\n'

    # ---------- output ----------
    def raw(self, text):
        self.lines.append(text)

    def emit(self, text, node):
        self.lines.append('    ' * self.level + text)                     # G4
        self.line_map[len(self.lines)] = node.line

    def block(self, stmts):
        self.level += 1
        start = len(self.lines)
        for s in stmts:
            self.stmt(s)
        if len(self.lines) == start:
            self.lines.append('    ' * self.level + 'pass')                # G4
        self.level -= 1

    # ---------- statements (G1) ----------
    def stmt(self, s):
        if isinstance(s, (A.UnitDecl, A.KindDecl)):
            return
        getattr(self, 'st_' + type(s).__name__)(s)

    def st_FnDecl(self, s):
        params = ', '.join(py_name(p.name) for p in s.params)
        self.emit(f'def {py_name(s.name)}({params}):', s)
        self.block(s.body)

    def st_Let(self, s):
        self.emit(f'{py_name(s.name)} = {self.expr(s.value)}', s)

    def st_Assign(self, s):
        self.emit(f'{py_name(s.name)} = {self.expr(s.value)}', s)

    def st_Return(self, s):
        self.emit(f'return {self.expr(s.value)}', s)

    def st_CallStmt(self, s):
        self.emit(self.expr(s.call), s)

    def st_While(self, s):
        self.emit(f'while {self.expr(s.cond)}:', s)
        self.block(s.body)

    def st_If(self, s, word='if'):
        self.emit(f'{word} {self.expr(s.cond)}:', s)
        self.block(s.then)
        els = s.els
        if els:
            if len(els) == 1 and isinstance(els[0], A.If) and els[0].elif_chain:   # D21
                self.st_If(els[0], 'elif')
            else:
                self.emit('else:', s)
                self.block(els)

    def st_Print(self, s):                                             # D23
        parts = []
        for a in s.args:
            text = self.scaled(self.expr(a.value), a.divisor, a.offset)
            parts.append((text, a.label))
        if len(parts) == 1:
            text, lab = parts[0]
            args = f'{text}, {lab!r}' if lab else text
        else:
            args = ', '.join(f'{t}, {l!r}' for t, l in parts)
        self.emit(f'us_print({args})', s)

    @staticmethod
    def scaled(text, divisor, offset):
        """(x - offset) / divisor, leaving out what is pointless."""
        if offset:
            text = f'({text} - {num_text(offset)})'
        if divisor != 1.0:
            text = f'({text} / {num_text(divisor)})'
        return text

    # ---------- expressions (G2, G3) ----------
    def expr(self, e) -> str:
        return getattr(self, 'ex_' + type(e).__name__)(e)

    def ex_Number(self, e):
        return num_text(e.value)

    def ex_UnitLiteral(self, e):
        return num_text(e.base_value)

    def ex_String(self, e):
        return repr(e.value)

    def ex_Bool(self, e):
        return 'True' if e.value else 'False'

    def ex_Name(self, e):
        if e.unit_value is not None:                                   # U4
            return num_text(e.unit_value)
        if e.const is not None:                                        # D22
            return e.const
        return py_name(e.name)

    def ex_BinOp(self, e):
        return f'({self.expr(e.left)} {e.op} {self.expr(e.right)})'

    ex_Compare = ex_BinOp

    def ex_Logic(self, e):
        return f'({self.expr(e.left)} {e.op} {self.expr(e.right)})'

    def ex_Not(self, e):
        return f'(not {self.expr(e.operand)})'

    def ex_Neg(self, e):
        return f'(-{self.expr(e.operand)})'

    def ex_Power(self, e):                                             # G8
        return f'math.pow({self.expr(e.base)}, {self.expr(e.exp)})'

    def ex_Call(self, e):
        args = [self.expr(a) for a in e.args]
        if e.py_func is not None:                                      # a built-in
            if e.name == 'kelvin':                                     # D13
                return args[0]
            return f'{e.py_func}({", ".join(args)})'
        if e.arg_scale:                                                # E3, E6
            args = [self.scaled(a, d, o) for a, (d, o) in zip(args, e.arg_scale)]
        text = f'{py_name(e.name)}({", ".join(args)})'
        if e.ret_scale:
            factor, offset = e.ret_scale
            if factor != 1.0:
                text = f'({text} * {num_text(factor)})'
            if offset:
                text = f'({text} + {num_text(offset)})'
        return text


def generate(program, filename='program.us') -> str:
    return Generator().run(program, filename)
